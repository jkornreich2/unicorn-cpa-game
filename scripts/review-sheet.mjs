// Writes REVIEW.md: every case with its correct answer, for CPA review on GitHub.
//   node scripts/review-sheet.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROUND_NAME = { seed: "Seed", "series-a": "Series A", ipo: "IPO" };
const usd = (n) => "$" + n.toLocaleString("en-US");
const quote = (t) => t.split("\n").map((l) => "> " + l).join("\n");

let out = `# Case review sheet

Generated from \`content/cases/\`. Do not edit this file; edit the case files and run \`npm run review\`.

**To sign off a case:** open its file in \`content/cases/\`, find its \`id\`, and fill in
\`"reviewedBy": "Your Name, CPA"\` and \`"currentAsOf": "YYYY-MM-DD"\`. To fix one, edit the text there.

`;

const rows = [];
for (const sec of ["FAR", "AUD", "REG", "TCP"]) {
  const path = join(root, `content/cases/${sec.toLowerCase()}.json`);
  if (!existsSync(path)) continue;
  const list = JSON.parse(readFileSync(path, "utf8"));
  out += sec === "TCP" ? `## TCP (parked: not in the core game yet)\n\n` : `## ${sec}\n\n`;
  for (const c of list) {
    const r = c.review || {};
    const status = r.reviewedBy ? `Reviewed by ${r.reviewedBy}, current as of ${r.currentAsOf || "?"}` : "**Not reviewed**";
    rows.push([c.id, ROUND_NAME[c.round], c.topic, c.studyArea || "", r.reviewedBy ? "Yes" : "No"]);
    out += `### ${c.id} · ${c.topic} (${ROUND_NAME[c.round]})\n\n${c.studyArea ? "Study area: " + c.studyArea + " · " : ""}${status}\n\n`;
    out += `*${c.from}:*\n\n${quote(c.message)}\n\n**Question:** ${c.question}\n\n`;
    if (c.type === "mcq") {
      out += c.options.map((o, k) => `${k === c.answer ? "- [x] **" + o + "** ← correct" : "- [ ] " + o}`).join("\n") + "\n\n";
    } else if (c.type === "num") {
      out += `**Correct answer:** ${usd(c.answer)}${c.tolerance ? ` (accepts ±${usd(c.tolerance)})` : ""}\n\n`;
    } else {
      out += `**Correct entry:** Dr ${c.debit} ${usd(c.amount)} / Cr ${c.credit} ${usd(c.amount)}\n\n`;
      out += `Accounts offered: ${c.accounts.join(", ")}\n\n`;
    }
    out += `**Explanation shown to player:** ${c.explanation}\n\n**Exam takeaway:** ${c.takeaway}\n\n---\n\n`;
  }
}

// Coverage: how many cases each blueprint topic has, grouped by content area.
let coverage = "";
for (const sec of ["FAR", "AUD", "REG", "TCP"]) {
  const op = join(root, `content/outline/${sec.toLowerCase()}.json`), cp = join(root, `content/cases/${sec.toLowerCase()}.json`);
  if (!existsSync(op) || !existsSync(cp)) continue;
  const outline = JSON.parse(readFileSync(op, "utf8")), list = JSON.parse(readFileSync(cp, "utf8"));
  const all = outline.areas.flatMap((x) => x.modules.map((m) => `${x.area} · ${m}`));
  const hit = all.filter((m) => list.some((c) => c.studyArea === m)).length;
  coverage += `### ${sec}: ${hit} of ${all.length} blueprint topics have a case\n\n| Topic | Cases |\n|---|---|\n`;
  for (const x of outline.areas) {
    const n = list.filter((c) => (c.studyArea || "").startsWith(x.area + " · ")).length;
    coverage += `| **${x.area}: ${x.name}** (exam weight ${x.weight}) | **${n}** |\n`;
    coverage += x.modules.map((m) => { const k = list.filter((c) => c.studyArea === `${x.area} · ${m}`).length; return `| ${m} | ${k || "—"} |`; }).join("\n") + "\n";
  }
  coverage += `\nOutline source: ${outline.source}\n\n`;
}

const table = "| ID | Round | Topic | Study area | Reviewed |\n|---|---|---|---|---|\n" + rows.map((r) => `| ${r.join(" | ")} |`).join("\n") + "\n\n";
out = out.replace("## FAR", "## Status\n\n" + table + (coverage ? "## Coverage\n\n" + coverage : "") + "## FAR");
writeFileSync(join(root, "REVIEW.md"), out);
console.log(`Wrote REVIEW.md (${rows.length} cases, ${rows.filter((r) => r[4] === "No").length} not reviewed)`);
